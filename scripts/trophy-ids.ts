/**
 * Prints every trophy ID the game can award, as a list to read rather than a table to parse, and writes
 * `docs/trophy-ids.md`.
 *
 * Two sources, and the split is the whole point of the script:
 *
 *   - LEAGUES come from the SAVE's own competition catalogue, so the list contains exactly the leagues this
 *     game ships and nothing invented. The id in `league-<id>.png` is the save's own `league_id`.
 *   - CUPS and INTERNATIONAL competitions come from the authored catalogue, because the save ships domestic
 *     cups with an EMPTY name (they are localised in the game, not stored) so there is no id to key on.
 *
 * The document's hand-written header lives in this file rather than in the document, because a header that
 * lives in a generated file is what makes a generated file un-regenerable: writing the list by hand and
 * writing it by script drift apart, and the drift is invisible until someone reads the wrong one.
 *
 *   npx tsx scripts/trophy-ids.ts            # the whole list
 *   npx tsx scripts/trophy-ids.ts --write    # ...and write docs/trophy-ids.md
 *   npx tsx scripts/trophy-ids.ts --artwork  # just the artwork filenames, one per line
 *
 * Reads only, except with --write, which touches one markdown file.
 */
import fs from "fs";
import path from "path";
import { db } from "../src/lib/db/client";
import { leagues } from "../src/lib/db/schema";
import { desc, eq } from "drizzle-orm";
import { careers } from "../src/lib/db/schema";
import {
  catalogueKeys,
  continentalFor,
  domesticCupsFor,
  internationalTrophies,
  isInternationalKey,
  type CupDefinition,
} from "../src/lib/trophies/catalogue";
import { leagueLabel } from "../src/lib/ui/leagues";

/** The pools the game uses for editing and career scaffolding. Not trophies, never offered. */
const NOT_TROPHIES = new Set([0, 76, 78, 211, 216, 222, 255, 382, 384, 2000, 2028, 2092, 2136, 2226]);

const ARTWORK_ONLY = process.argv.includes("--artwork");
const WRITE = process.argv.includes("--write");

/** The hand-written half of `docs/trophy-ids.md`. Everything after it is generated. */
const HEADER = `# Trophy IDs

Every trophy the game can award, and the artwork filename each one looks for.

Generated by \`npx tsx scripts/trophy-ids.ts --write\`. Regenerate it after a sync, because the league list
is read from the SAVE's own competition catalogue: that is what makes it strict, since the ids below are the
ones the game itself ships rather than a list somebody typed out.

Two sources, and the split matters. The LEAGUES come from the save, so \`league-<id>.png\` uses the save's own
\`league_id\` and needs no mapping table. The CUPS and the INTERNATIONAL competitions are authored in
\`src/lib/trophies/catalogue.ts\`, because the save ships domestic cups with an EMPTY name (they are localised
in the game, not stored), so there is no id to key them on.

Drop artwork in \`public/trophies/<name>.png\`. A key with no file gets a drawn placeholder, never a broken
image, so the list can be filled in over time.

## How the cup list was checked (2026-10-12)

A licensed-competitions list is about BRANDING, not about which cups are played: the KNVB Beker is on no
licence list and is still played in a Dutch career. So the list below was checked against the save's own
competition table (which binds exactly four competitions to England: FA Cup, EFL Cup, EFL Trophy, Community
Shield) and against the two titles' own competition lists. That check REMOVED the FIFA Confederations Cup,
the FIFA Club World Cup, the UEFA Nations League and the Supercopa de España, and ADDED the two competitions
the list had been missing: the UEFA Super Cup and the CONMEBOL Recopa. \`src/lib/trophies/catalogue.ts\` holds
the full reasoning, and a competition a manager finds he can win goes back with one line there.

\`\`\`
npx tsx scripts/trophy-ids.ts            # this document
npx tsx scripts/trophy-ids.ts --artwork  # just the filenames, one per line
\`\`\`

---

`;

/** Everything the run prints. Collected rather than printed so --write can emit exactly what was shown. */
const out: string[] = [];

/**
 * One line, to the document and to the terminal.
 *
 * Echoing as it goes rather than printing the collection at the end is what keeps the terminal's reading
 * order identical to the document's: the heading lands above the list it heads, not after it.
 */
function say(line = ""): void {
  out.push(line);
  if (!WRITE) console.log(line);
}

function cupLine(cup: CupDefinition): string {
  const tiers = cup.openToTiers === null ? "every tier" : `tiers ${cup.openToTiers.join(", ")}`;
  return `  ${cup.key.padEnd(24)} ${cup.name.padEnd(34)} ${tiers}`;
}

async function main(): Promise<void> {
  const career = await db.select().from(careers).orderBy(desc(careers.updatedAt)).limit(1).get();
  if (!career) {
    console.log("no career in the database: run a sync first, because the league list comes from the save");
    return;
  }

  const catalogue = await db.select().from(leagues).where(eq(leagues.careerId, career.id));

  // Strict: a league row only counts when the game named it, gave it a country and gave it a tier. That is
  // what excludes the editing pools, the youth squad league and the women's divisions in one rule. A row whose
  // name is a continental competition is excluded too: the save files those as "leagues", and they belong in
  // the continental section further down where they are listed once.
  const continentalNames = new Set(
    [...new Set(catalogue.map((row) => row.countryId).filter((id): id is number => id !== null))]
      .flatMap((countryIdTmp) => continentalFor(countryIdTmp))
      .map((cup) => cup.name.toLowerCase())
  );
  const named = catalogue
    .filter(
      (row) =>
        row.name.trim() !== "" &&
        row.countryId !== null &&
        !row.isWomenCompetition &&
        row.level !== null &&
        row.level >= 1 &&
        row.level <= 7 &&
        !NOT_TROPHIES.has(row.leagueId) &&
        !continentalNames.has(row.name.replace(/\s*\(\d+\)\s*$/, "").toLowerCase())
    )
    .sort(
      (left, right) =>
        (left.countryName ?? "zz").localeCompare(right.countryName ?? "zz") ||
        (left.level ?? 99) - (right.level ?? 99) ||
        left.leagueId - right.leagueId
    );

  if (ARTWORK_ONLY) {
    for (const row of named) console.log(`league-${row.leagueId}.png`);
    for (const key of catalogueKeys()) {
      if (!key.startsWith("league-")) console.log(`${key}.png`);
    }
    return;
  }

  say(`TROPHY IDS  (from ${career.clubName}, save ${career.id})`);
  say("The league ids below are the save's own, so they are exactly the competitions the game ships.\n");

  say("LEAGUE TITLES - artwork is league-<id>.png\n");
  let country = "";
  for (const row of named) {
    const name = row.countryName ?? "Unknown nation";
    if (name !== country) {
      country = name;
      say(`\n  ${country.toUpperCase()}`);
    }
    say(
      `    league-${String(row.leagueId).padEnd(6)} ${leagueLabel(row.name, row.leagueId).padEnd(38)} tier ${row.level}`
    );
  }

  say("\n\nDOMESTIC CUPS - artwork is <key>.png\n");
  const nations = [...new Set(named.map((row) => row.countryId))].filter(
    (id): id is number => id !== null
  );
  for (const nationId of nations.sort((a, b) => a - b)) {
    const cups = domesticCupsFor(nationId);
    if (cups.length === 0) continue;
    const label = named.find((row) => row.countryId === nationId)?.countryName ?? `nation ${nationId}`;
    say(`\n  ${label.toUpperCase()} (nation ${nationId})`);
    for (const cup of cups) say(cupLine(cup));
  }

  say("\n\nCONTINENTAL - artwork is <key>.png\n");
  const seenRegion = new Set<string>();
  for (const nationId of nations) {
    for (const cup of continentalFor(nationId)) {
      if (seenRegion.has(cup.key)) continue;
      seenRegion.add(cup.key);
      say(cupLine(cup));
    }
  }

  say("\n\nINTERNATIONAL - artwork is <key>.png");
  say("Recorded by hand: nothing in a club save holds a national-team result.\n");
  for (const competition of internationalTrophies()) say(cupLine(competition));

  say(
    `\n\nTOTALS  ${named.length} league titles, ${catalogueKeys().filter((key) => isInternationalKey(key)).length} international, ${catalogueKeys().length} artwork files in all`
  );

  if (!WRITE) {
    return;
  }

  // UTF-8, explicitly. The document used to be produced by redirecting this script in Windows PowerShell,
  // which writes UTF-16LE with a byte order mark - so a text file about filenames was unreadable to half
  // the tools that touch it. Node writes what it is told here.
  const target = path.join(process.cwd(), "docs", "trophy-ids.md");
  fs.writeFileSync(target, `${HEADER}${out.join("\n")}\n`, "utf8");
  console.log(`wrote ${target} (${out.length} lines) from ${career.id}`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
