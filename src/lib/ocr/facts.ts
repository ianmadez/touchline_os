/**
 * The Match Facts a scan read, as they are stored, and the rules that decide whether to keep them.
 *
 * WHAT THIS IS FOR. Five figures the scanner read flow into the five boxes the manager can edit, which is what
 * the app has always done. Everything else the screens carry used to be thrown away. It is now kept as FACTS:
 * the screen's own figures, per club, exactly as they were printed, so a debrief can say what the game said
 * rather than only what fitted in a box.
 *
 * TWO SOURCES, NEVER BLENDED. The boxes are the manager's figures and can be edited; the facts are the screen's
 * figures and never change once stored. Where a box was edited after a read, both are kept and the box wins for
 * anything that consumes it, because that is the figure the manager is looking at.
 *
 * ALL OR NOTHING, PER SCREEN. A screen is stored only when every required row was read AND every sum it owes
 * holds. A half read screen is a set of figures with no way to say which half is missing, and the sums that
 * would have caught a misread are exactly the ones the missing row was part of.
 *
 * ABSENT IS NOT ZERO. A screen that was never scanned has no group at all, which is a different claim from a
 * group of zeroes: one says nothing happened, the other says nobody looked.
 */

import { SCREENS, screenRows, type FactKey, type FactScreen, type ScreenId } from "./layouts";
import type { ScreenValue } from "./extract";

/** The version of the shape below. Additive changes keep it, a change of meaning moves it. */
export const FACTS_VERSION = 1;

/** One figure, both clubs, exactly as the screen printed it. */
export interface FactPair {
  us: number;
  them: number;
}

export type ScreenFacts = Partial<Record<FactKey, FactPair>>;

export interface MatchFacts {
  v: number;
  summary?: ScreenFacts;
  shooting?: ScreenFacts;
  passing?: ScreenFacts;
  defending?: ScreenFacts;
}

export function emptyFacts(): MatchFacts {
  return { v: FACTS_VERSION };
}

/** True when no screen was kept. */
export function factsAreEmpty(facts: MatchFacts | null | undefined): boolean {
  if (!facts) return true;
  return SCREENS.every((screen) => screenFactsOf(facts, screen.id) === undefined);
}

export function screenFactsOf(facts: MatchFacts | null | undefined, id: ScreenId): ScreenFacts | undefined {
  return facts?.[id.toLowerCase() as "summary" | "shooting" | "passing" | "defending"];
}

/** The pair stored for one key, or null when that screen or that row was never read. */
export function factValue(
  facts: MatchFacts | null | undefined,
  id: ScreenId,
  key: FactKey
): FactPair | null {
  return screenFactsOf(facts, id)?.[key] ?? null;
}

/**
 * The sums a screen owes, and the reason each exists.
 *
 * A sum is a HARD check: the figures on a screen are generated by the game from one another, so a set that does
 * not add up contains a misread, and there is no way to tell which figure is the wrong one. The screen is kept
 * whole or not at all.
 */
interface SumRule {
  /** The row the members are expected to add up to. */
  total: FactKey;
  members: FactKey[];
  /** How the rule is described when it fails, in the manager's words. */
  label: string;
}

export const SUM_RULES: Partial<Record<ScreenId, SumRule[]>> = {
  SHOOTING: [
    { total: "totalShots", members: ["onTarget", "offTarget", "blocked"], label: "on target, off target and blocked" },
    {
      total: "totalShots",
      members: ["normal", "finesse", "header", "power", "volley", "chip", "setPieces"],
      label: "the seven shot types",
    },
    { total: "totalShots", members: ["insideBox", "outsideBox"], label: "inside and outside the box" },
    { total: "totalShots", members: ["nearSide", "farSide"], label: "near side and far side" },
  ],
  PASSING: [
    {
      total: "totalPasses",
      members: ["completed", "intercepted", "offside", "other"],
      label: "completed, intercepted, offside and other",
    },
  ],
};

/**
 * What one image's read of one screen produced, judged.
 *
 * `group` is null when the screen is not stored, and `refusal` then says why in one line: the manager is the one
 * who can look at his own screenshot, so the line names the row or the sum rather than the rule's name.
 */
export interface FactGroupResult {
  screen: ScreenId;
  group: ScreenFacts | null;
  refusal: string | null;
  /** The keys whose figure had to be worked out from a sum. */
  derived: FactKey[];
  /** The lower of the two confidences of every figure kept, so the screen is as trusted as its worst row. */
  confidence: number;
}

/** The two sides of a key, or null when either side is missing. */
const pairOf = (values: ScreenFacts, key: FactKey): FactPair | null => values[key] ?? null;

/**
 * Judges one screen's read, deriving a single unreadable figure where a sum allows it.
 *
 * Deriving is deliberately narrow. Exactly one missing figure in a group whose total is known is arithmetic, and
 * it is marked as derived and counted as lower confidence. Two missing figures is not arithmetic, it is a
 * capture that did not read, and guessing there would be inventing the game's figures.
 */
export function evaluateScreen(
  screen: FactScreen,
  reading: Map<FactKey, ScreenValue>
): FactGroupResult {
  const failures: string[] = [];
  const derived: FactKey[] = [];
  const values: ScreenFacts = {};
  let confidence = 1;

  for (const value of reading.values()) {
    values[value.key] = { us: value.us, them: value.them };
    confidence = Math.min(confidence, value.confidence);
  }

  for (const rule of SUM_RULES[screen.id] ?? []) {
    /*
      Presence is decided ONCE, before either side is looked at.

      Deciding it inside the side loop reads a figure derived for our side as though it had been read, and then
      checks the other side against a zero that was never on the screen. One pass over the sides with the same
      view of what was read is the only version that derives the right number.
    */
    const present = rule.members.filter((key) => pairOf(values, key) !== null);
    const missing = rule.members.filter((key) => pairOf(values, key) === null);

    if (missing.length > 1) {
      failures.push(`only ${present.length} of ${rule.members.length} rows behind ${rule.label} could be read`);
      continue;
    }

    if (missing.length === 1) {
      const key = missing[0];
      const existing: FactPair | undefined = values[key];
      const next: FactPair = { us: existing?.us ?? 0, them: existing?.them ?? 0 };
      let ok = true;
      for (const side of ["us", "them"] as const) {
        if (existing?.[side] !== undefined) continue;
        const total = pairOf(values, rule.total);
        if (total === null) {
          ok = false;
          break;
        }
        const rest = present.reduce((sum, member) => sum + (pairOf(values, member)?.[side] ?? 0), 0);
        if (total[side] - rest < 0) {
          ok = false;
          break;
        }
        next[side] = total[side] - rest;
      }
      if (!ok) {
        failures.push(`${rule.label} do not add up to ${rule.total} on one side`);
        continue;
      }
      values[key] = next;
      derived.push(key);
      // A derived figure is arithmetic rather than a reading, so it is trusted less than one that was seen.
      confidence = Math.min(confidence, 0.65);
      continue;
    }

    if (pairOf(values, rule.total) === null) {
      // The total is the one unreadable figure in its group, so it comes off the rows that were read, both sides
      // at once: deriving one side and then checking the other against a zero that was never on the screen is
      // how a good capture gets refused.
      values[rule.total] = {
        us: rule.members.reduce((sum, key) => sum + (pairOf(values, key)?.us ?? 0), 0),
        them: rule.members.reduce((sum, key) => sum + (pairOf(values, key)?.them ?? 0), 0),
      };
      derived.push(rule.total);
      confidence = Math.min(confidence, 0.65);
      continue;
    }

    for (const side of ["us", "them"] as const) {
      const total = pairOf(values, rule.total);
      if (total === null) continue;
      const sum = rule.members.reduce((running, key) => running + (pairOf(values, key)?.[side] ?? 0), 0);
      if (sum !== total[side]) {
        failures.push(`${rule.label} add up to ${sum} rather than ${total[side]} on one side`);
      }
    }
  }

  // Possession is the one sum that runs ACROSS the two sides: the two figures are one split of the same ball.
  if (screen.id === "SUMMARY") {
    const possession = pairOf(values, "possessionPct");
    if (possession !== null && Math.abs(possession.us + possession.them - 100) > 1) {
      failures.push(`possession adds up to ${possession.us + possession.them} rather than 100`);
    }
  }

  const missingRequired = screenRows(screen)
    .filter((row) => row.required && row.key !== null)
    .map((row) => row.key as FactKey)
    .filter((key) => pairOf(values, key) === null || values[key]?.us === undefined || values[key]?.them === undefined);

  if (failures.length > 0) {
    return { screen: screen.id, group: null, refusal: failures[0], derived, confidence };
  }
  if (missingRequired.length > 0) {
    return {
      screen: screen.id,
      group: null,
      refusal: `${missingRequired.length} of its rows could not be read`,
      derived,
      confidence,
    };
  }

  return { screen: screen.id, group: values, refusal: null, derived, confidence };
}

/**
 * Folds one judged screen into the facts.
 *
 * The newest read of a screen wins whole: a second capture of the same screen is usually a scroll further down,
 * and merging two captures row by row would mix a scrolled read with an unscrolled one. Replacing the group
 * keeps every figure on a screen from the same look at it.
 */
export function mergeScreenFacts(facts: MatchFacts, result: FactGroupResult): MatchFacts {
  if (result.group === null) return facts;
  const key = result.screen.toLowerCase() as "summary" | "shooting" | "passing" | "defending";
  return { ...facts, v: FACTS_VERSION, [key]: result.group };
}

/**
 * The cross checks, which are NOTES rather than drops.
 *
 * Two screens of the same match are two screenshots, and a figure can disagree across them without either being
 * unreadable: the game itself disagrees, which is exactly why tackles won is not checked at all. So a mismatch is
 * reported to the manager and the figures are kept, because dropping a screen that passed its own sums over a
 * difference the game also shows would lose real data to a rounding of the rules.
 */
export function crossScreenNotes(facts: MatchFacts): string[] {
  const notes: string[] = [];
  const summary = screenFactsOf(facts, "SUMMARY");
  if (summary === undefined) return notes;

  /**
   * One figure the Summary screen and another screen both carry.
   *
   * The two screens do not always name the same figure the same way: the Summary screen's row is Shots and the
   * Shooting screen's is Total shots. The pair is named here rather than assumed, so the comparison is between
   * the two rows that are actually the same number.
   */
  const compareAcross = (
    left: [ScreenId, FactKey],
    right: [ScreenId, FactKey],
    text: string
  ): void => {
    const a = factValue(facts, left[0], left[1]);
    const b = factValue(facts, right[0], right[1]);
    if (a === null || b === null) return;
    const label = SCREENS.find((entry) => entry.id === right[0])?.label ?? right[0];
    for (const side of ["us", "them"] as const) {
      if (a[side] !== b[side]) {
        notes.push(`${text} reads ${a[side]} on the Summary screen and ${b[side]} on the ${label} screen`);
        return;
      }
    }
  };

  compareAcross(["SUMMARY", "shots"], ["SHOOTING", "totalShots"], "Shots");
  compareAcross(["SUMMARY", "passes"], ["PASSING", "totalPasses"], "Passes");
  compareAcross(["SUMMARY", "interceptions"], ["DEFENDING", "interceptions"], "Interceptions");
  compareAcross(["SUMMARY", "saves"], ["DEFENDING", "saves"], "Saves");
  compareAcross(["SUMMARY", "foulsCommitted"], ["DEFENDING", "foulsCommitted"], "Fouls committed");
  compareAcross(["SUMMARY", "yellowCards"], ["DEFENDING", "yellowCards"], "Yellow cards");

  // Summary Tackles is standing plus sliding on Defending, and the game's own data disagrees, so this one is
  // reported the same way rather than treated as a failure.
  const tackles = summary.tackles;
  const standing = factValue(facts, "DEFENDING", "standingTackles");
  const sliding = factValue(facts, "DEFENDING", "slidingTackles");
  if (tackles !== undefined && standing !== null && sliding !== null) {
    for (const side of ["us", "them"] as const) {
      if (tackles[side] !== standing[side] + sliding[side]) {
        notes.push(
          `Tackles reads ${tackles[side]} on the Summary screen and ${standing[side] + sliding[side]} across the Defending screen`
        );
        break;
      }
    }
  }

  return notes;
}

/**
 * The five figures the boxes take, read out of the facts.
 *
 * The boxes stay the source of truth for those five, and this is only what a scan can offer them: shots from
 * Summary or the Shooting total, inside box from Shooting, expected goals and possession and passes from
 * Summary. Anything not read there comes back null and the box is left exactly as it was.
 */
export function boxValuesFromFacts(facts: MatchFacts): {
  shots: number | null;
  shotsInsideBox: number | null;
  expectedGoalsReported: number | null;
  possession: number | null;
  passesCompleted: number | null;
} {
  const pick = (id: ScreenId, key: FactKey, side: "us" | "them"): number | null =>
    factValue(facts, id, key)?.[side] ?? null;
  return {
    shots: pick("SUMMARY", "shots", "us") ?? pick("SHOOTING", "totalShots", "us"),
    shotsInsideBox: pick("SHOOTING", "insideBox", "us"),
    expectedGoalsReported: pick("SUMMARY", "expectedGoals", "us"),
    possession: pick("SUMMARY", "possessionPct", "us"),
    passesCompleted: pick("SUMMARY", "passes", "us") ?? pick("PASSING", "totalPasses", "us"),
  };
}

/**
 * Validates stored facts on the way in.
 *
 * Every value is a number, both sides are present, and only keys the layout knows are kept, so a crafted request
 * cannot put arbitrary keys into a payload every reader would then have to tolerate. A screen with nothing left
 * in it after that is dropped rather than stored empty: an empty group would claim a screen was read.
 */
export function normaliseFacts(raw: unknown): MatchFacts | null {
  if (raw === null || typeof raw !== "object") return null;
  const input = raw as { v?: unknown } & Record<string, unknown>;
  const facts: MatchFacts = { v: FACTS_VERSION };
  let kept = 0;

  for (const screen of SCREENS) {
    const key = screen.id.toLowerCase() as "summary" | "shooting" | "passing" | "defending";
    const candidate = input[key];
    if (candidate === null || typeof candidate !== "object") continue;
    const group: ScreenFacts = {};
    const known = new Set(screenRows(screen).map((row) => row.key));
    for (const [field, value] of Object.entries(candidate as Record<string, unknown>)) {
      if (!known.has(field as FactKey)) continue;
      if (value === null || typeof value !== "object") continue;
      const pair = value as { us?: unknown; them?: unknown };
      if (typeof pair.us !== "number" || typeof pair.them !== "number") continue;
      if (!Number.isFinite(pair.us) || !Number.isFinite(pair.them)) continue;
      if (pair.us < 0 || pair.them < 0) continue;
      group[field as FactKey] = { us: pair.us, them: pair.them };
    }
    if (Object.keys(group).length > 0) {
      facts[key] = group;
      kept += 1;
    }
  }

  return kept === 0 ? null : facts;
}
